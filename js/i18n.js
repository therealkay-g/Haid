  function swapMessages(lang) {
    document.querySelectorAll('[data-message]').forEach(function (el) {
      if (!el.getAttribute('data-message-fr')) {
        el.setAttribute('data-message-fr', el.getAttribute('data-message') || '');
      }
      var fr = el.getAttribute('data-message-fr');
      if (lang === 'en') {
        var done = false;
        for (var i = 0; i < MSGS.length; i++) {
          if (fr === MSGS[i][0]) { el.setAttribute('data-message', MSGS[i][1]); done = true; break; }
        }
        if (!done && fr.indexOf(PROJ_FR) === 0) {
          el.setAttribute('data-message', PROJ_EN + fr.slice(PROJ_FR.length));
        }
      } else {
        el.setAttribute('data-message', fr);
      }
    });
  }

  function currentLang() {
    try { return localStorage.getItem('haid-lang') === 'en' ? 'en' : 'fr'; }
    catch (e) { return 'fr'; }
  }

  function apply(lang) {
    var table = dict[lang] || dict.fr;
    document.documentElement.setAttribute('lang', lang);
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = table[el.getAttribute('data-i18n')];
      if (typeof v === 'string') el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var v = table[el.getAttribute('data-i18n-html')];
      if (typeof v === 'string') el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var v = table[el.getAttribute('data-i18n-ph')];
      if (typeof v === 'string') el.setAttribute('placeholder', v);
    });
    swapMessages(lang);
    var page = (location.pathname.split('/').pop() || 'index.html').split('?')[0].split('#')[0];
    if (!page) page = 'index.html';
    var t = (TITLES[lang] || {})[page];
    if (t) {
      document.title = t[0];
      var meta = document.querySelector('meta[name="description"]');
      if (meta) meta.setAttribute('content', t[1]);
    }
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
    try { localStorage.setItem('haid-lang', lang); } catch (e) {}
  }

  document.addEventListener('DOMContentLoaded', function () {
    apply(currentLang());
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.addEventListener('click', function () { apply(btn.getAttribute('data-lang')); });
    });
  });

  return { apply: apply, current: currentLang, dict: dict };
